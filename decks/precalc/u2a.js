// Piecewise linear helpers for the graphs below.
const pw = (pts) => (x) => {
  for (let i = 0; i < pts.length - 1; i++) {
    const [ax, ay] = pts[i], [bx, by] = pts[i + 1];
    if (x >= ax - 1e-9 && x <= bx + 1e-9) return ay + ((by - ay) * (x - ax)) / (bx - ax);
  }
  return NaN;
};
