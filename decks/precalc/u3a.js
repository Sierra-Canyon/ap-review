const PI = Math.PI;
// graph() labels ticks with decimals. piGraph relabels the x-axis ticks as multiples of pi/den (pi/4, 3pi/2, ...).
const gcd = (a, b) => (b ? gcd(b, a % b) : a);
function piLabel(v, den) {
  const k = Math.round(v / (PI / den));
  if (k === 0) return "0";
  const g = gcd(Math.abs(k), den), n = k / g, d = den / g;
  const top = (n < 0 ? "−" : "") + (Math.abs(n) === 1 ? "" : Math.abs(n)) + "π";
  return d === 1 ? top : top + "/" + d;
}
function piGraph(o, den) {
  return graph(o).replace(/(<text class="g-tick"[^>]*text-anchor="middle">)([^<]+)(<\/text>)/g, (m, a, t, c) => a + piLabel(parseFloat(t.replace("−", "-")), den) + c);
}
