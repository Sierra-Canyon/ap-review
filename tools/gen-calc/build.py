"""Builds the generated AP Calculus review files. Run from the repo root: python3 tools/gen-calc/build.py"""
import json, random, sys, os
sys.path.insert(0, os.path.dirname(__file__))
from core import Skip, write_deck
import importlib

NEED = json.load(open(os.path.join(os.path.dirname(__file__), "need.json")))

def build(unit, seed=20261106):
    mod = importlib.import_module(f"u{unit}")
    r = random.Random(seed + unit)
    items, sets = [], {}
    topics = sorted([k for k in NEED if k.split(".")[0] == str(unit)], key=lambda k: int(k.split(".")[1]))
    for tp in topics:
        n = NEED[tp]
        if n <= 0: continue
        got, seen, tries = [], set(), 0
        if tp in getattr(mod, "GRAPH_TEMPLATES", {}):
            while len(got) < n and tries < 200:
                tries += 1
                try:
                    its, sid, code = mod.GRAPH_TEMPLATES[tp](r)
                except Skip:
                    continue
                sets[sid] = code
                got.extend(its)
            got = got[:max(n, len(got))]
        else:
            temps = mod.TEMPLATES.get(tp, [])
            if not temps:
                print("no templates for", tp); continue
            k = 0
            while len(got) < n and tries < 2000:
                tries += 1
                fn = temps[k % len(temps)]; k += 1
                if sum(1 for g in got if g.get("_t") == fn.__name__) >= getattr(fn, "max", 99): continue
                try:
                    it = fn(r)
                except Skip:
                    continue
                key = (fn.__name__, it["choices"][0])
                if key in seen: continue
                seen.add(key); it["_t"] = fn.__name__; got.append(it)
        if len(got) < n: print(f"topic {tp}: only {len(got)} of {n}")
        items.extend(got)
    return items, sets

if __name__ == "__main__":
    units = [int(a) for a in sys.argv[1:]] or [1]
    if len(units) > 1:
        # Each unit's module may adjust how its deck is written (difficulty, sets drawn by templates), so every unit is
        # built in its own process, exactly as `build.py <N>` builds it alone.
        import subprocess
        for unit in units:
            subprocess.run([sys.executable, __file__, str(unit)], check=True)
        sys.exit(0)
    for unit in units:
        items, sets = build(unit)
        header = (f"// AP Calculus AB review, Unit {unit}: more multiple choice, generated by tools/gen-calc (python3 tools/gen-calc/build.py {unit}).\n"
                  "// Added 11/6 to bring each topic to at least 60 percent of the number of practice questions Albert has for it.\n"
                  "// Every key and every wrong choice is computed from a named mistake; do not edit by hand, change the template and rebuild.")
        write_deck(f"decks/calc/u{unit}x.js", header, sets, items, unit, f"c{unit}x")
        print(f"decks/calc/u{unit}x.js: {len(items)} items, {len(sets)} sets")
